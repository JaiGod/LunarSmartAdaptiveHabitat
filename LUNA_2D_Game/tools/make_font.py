PX = 100
def build(out):
    order = [".notdef", "space"] + ["u%04X" % ord(c) for c in G]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {32: "space"}
    for c in G: cmap[ord(c)] = "u%04X" % ord(c)
    fb.setupCharacterMap(cmap)
    glyphs, metrics = {}, {}
    pen = TTGlyphPen(None); glyphs[".notdef"] = pen.glyph(); metrics[".notdef"] = (600, 0)
    pen = TTGlyphPen(None); glyphs["space"] = pen.glyph(); metrics["space"] = (400, 0)
    for c, rows in G.items():
        name = "u%04X" % ord(c); pen = TTGlyphPen(None)
        w = max(len(r) for r in rows)
        for r, row in enumerate(rows):
            x = 0
            while x < len(row):
                if row[x] == "#":
                    x0 = x
                    while x < len(row) and row[x] == "#": x += 1
                    y0 = (6 - r) * PX
                    pen.moveTo((x0 * PX, y0)); pen.lineTo((x0 * PX, y0 + PX)); pen.lineTo((x * PX, y0 + PX)); pen.lineTo((x * PX, y0)); pen.closePath()
                else:
                    x += 1
        glyphs[name] = pen.glyph(); metrics[name] = ((w + 1) * PX, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "LUNA Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200, sTypoLineGap=0)
    fb.setupPost()
    fb.save(out)
    print("font:", len(G), "glyphs ->", out)

build(sys.argv[1])
